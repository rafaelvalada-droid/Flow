import asyncio,os
from playwright.async_api import async_playwright,expect
async def run():
 async with async_playwright() as p:
  browser=await p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
  page=await browser.new_page()
  await page.goto(os.environ.get('FLOW_TEST_URL','http://127.0.0.1:3000'))
  await page.locator('[data-page="projetos"]').click()
  await page.locator('[data-project="oferta"]').click()
  await expect(page.locator('.page-head h1')).to_have_text('Oferta de turmas')
  await page.locator('[data-action="new-initiative"]').click()
  await page.locator('#project-editor-form [name="name"]').fill('Projeto turmas 2027')
  await page.locator('#project-editor-form [type="submit"]').click()
  await page.locator('[data-page="projetos"]').click()
  await page.locator('[data-project="oferta"]').click()
  project=page.locator('.area-projects .card').filter(has_text='Projeto turmas 2027')
  await project.locator('[data-action="initiative-new-task"]').click()
  await expect(page.locator('#active-modal-form [name="project"]')).to_have_value('oferta')
  await page.locator('#active-modal-form [name="title"]').fill('Validar turmas')
  await page.locator('#active-modal-form [name="dueDate"]').fill(await page.evaluate('FlowWorkflow.localDate()'))
  await page.locator('#active-modal-form [type="submit"]').click()
  await expect(project.get_by_role('button',name='Validar turmas')).to_be_visible()
  await page.reload()
  await page.locator('[data-page="projetos"]').click()
  await page.locator('[data-project="oferta"]').click()
  await expect(project.get_by_role('button',name='Validar turmas')).to_be_visible()
  await page.locator('[data-action="area-new-task"]').click()
  await page.locator('#active-modal-form [name="title"]').fill('Tarefa solta da área')
  await page.locator('#active-modal-form [type="submit"]').click()
  await expect(page.get_by_role('button',name='Tarefa solta da área')).to_be_visible()
  await page.locator('[data-page="hoje"]').click()
  await expect(page.locator('.today-item').filter(has_text='Validar turmas')).to_be_visible()
  print('PASS Area opens its own page; tasks inherit area; project tasks stay grouped after reload and show up in Hoje')
  await browser.close()
asyncio.run(run())
